// Node + sharp: turn the masters in assets-src/ into responsive AVIF and WebP
// files in public/img/, and write app/content/images.ts (sizes for <Picture>).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "assets-src");
const out = join(root, "public", "img");
mkdirSync(out, { recursive: true });

const sets = {
  hero: { file: "hero.jpg", widths: [1280, 1920, 2560] },
  "hero-m": { file: "hero-m.jpg", widths: [720, 1080] },
  arch: { file: "arch.jpg", widths: [600, 900, 1200] },
  card: { file: "card.jpg", widths: [800, 1200, 1600] },
  "svc-stone": { file: "svc-stone.jpg", widths: [450, 675, 900] },
  "svc-leaves": { file: "svc-leaves.jpg", widths: [450, 675, 900] },
  "svc-ripples": { file: "svc-ripples.jpg", widths: [450, 675, 900] },
  "svc-hills": { file: "svc-hills.jpg", widths: [450, 675, 900] },
  "svc-dawn": { file: "svc-dawn.jpg", widths: [450, 675, 900] },
  "svc-rain": { file: "svc-rain.jpg", widths: [450, 675, 900] },
  "tile-water": { file: "tile-water.jpg", widths: [400, 800] },
  "tile-texture": { file: "tile-texture.jpg", widths: [400, 800] },
  portrait: { file: "portrait.jpg", widths: [400, 640] }, // never upscaled past 640
  "fog-a": { file: "fog-a.png", widths: [960, 1920], alpha: true },
  "fog-b": { file: "fog-b.png", widths: [960, 1920], alpha: true },
};

const manifest = {};
for (const [name, set] of Object.entries(sets)) {
  const input = sharp(join(src, set.file));
  const meta = await input.metadata();
  const widths = set.widths.filter((w) => w <= meta.width);
  for (const w of widths) {
    const resized = sharp(join(src, set.file)).resize({ width: w });
    await resized.clone().avif({ quality: set.alpha ? 60 : 52, effort: 6 }).toFile(join(out, `${name}-${w}.avif`));
    await resized.clone().webp({ quality: set.alpha ? 78 : 74, alphaQuality: 80 }).toFile(join(out, `${name}-${w}.webp`));
  }
  manifest[name] = { width: meta.width, height: meta.height, widths };
  console.log(name, widths.join(", "));
}

writeFileSync(
  join(root, "app", "content", "images.ts"),
  `// Generated by scripts/images.mjs. Do not edit by hand.\nexport const images = ${JSON.stringify(manifest, null, 2)} as const;\nexport type ImageName = keyof typeof images;\n`,
);
